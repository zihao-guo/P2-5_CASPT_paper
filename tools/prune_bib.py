#!/usr/bin/env python3
"""Usage: prune_bib.py main.tex in.bib out.bib"""
import re, sys

def strip_comments(t):
    return "\n".join(re.sub(r'(?<!\\)%.*', '', l) for l in t.split("\n"))

def main(tex, bib_in, bib_out):
    t = strip_comments(open(tex, encoding='utf8').read())
    keys = []
    for m in re.finditer(r'\\cite[a-zA-Z]*\*?\s*(?:\[[^\]]*\]\s*)*\{([^}]*)\}', t):
        for k in m.group(1).split(','):
            k = k.strip()
            if k and k not in keys:
                keys.append(k)
    src = open(bib_in, encoding='utf8').read()
    entries = {}  # key -> (start, end)
    order = []
    for m in re.finditer(r'^@(\w+)\s*\{\s*([^,\s]+)\s*,', src, re.M):
        if m.group(1).lower() in ('comment', 'string', 'preamble'):
            continue
        i = src.index('{', m.start()); depth = 0; j = i
        while j < len(src):
            if src[j] == '{': depth += 1
            elif src[j] == '}':
                depth -= 1
                if depth == 0: break
            j += 1
        entries[m.group(2)] = (m.start(), j + 1)
        order.append(m.group(2))
    missing = [k for k in keys if k not in entries]
    out = []
    for k in order:
        if k not in keys: continue
        s, e = entries[k]
        text = src[s:e]
        if k == 'guo2026extended':
            pre = src[:s].rstrip('\n').split('\n')[-2:]
            text = "\n".join(pre) + "\n" + text
        out.append(text)
    hdr = ("% Subset of the original manuscript's cas-refs.bib cited in main.tex, plus the extended-report entry.\n"
           "% Generated by tools/prune_bib.py; do not edit by hand.\n\n")
    open(bib_out, 'w', encoding='utf8').write(hdr + "\n\n".join(out) + "\n")
    print(len(keys), "keys:", ", ".join(keys))
    if missing:
        print("MISSING:", ", ".join(missing)); sys.exit(1)

if __name__ == '__main__':
    main(*sys.argv[1:4])
